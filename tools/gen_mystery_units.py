#!/usr/bin/env python3
"""Write src/MysteryXxx.cpp (one per pet) and src/MysteryFactory.cpp for the mystery egg build.

Each unit compiles the normal scene for ONE pet inside its own namespace; the factory picks one at runtime."""
import os
SPECIES = [  # (PET_ID, flag or None for the wolf, file stem, namespace, insect?)
    (0, None, "Wolf"), (1, "PET_FOX", "Fox"), (2, "PET_CAT", "Cat"), (3, "PET_BEAR", "Bear"), (4, "PET_BUTTERFLY", "Butterfly"),
    (5, "PET_GATOR", "Gator"), (6, "PET_CROC", "Croc"), (7, "PET_PIG", "Pig"), (8, "PET_DONKEY", "Donkey"),
    (9, "PET_UNICORN", "Unicorn"), (10, "PET_DRAGON", "Dragon"), (11, "PET_KITSUNE", "Kitsune"),
    (12, "PET_GRIFFIN", "Griffin"), (13, "PET_PHOENIX", "Phoenix")]
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src")
for pid, flag, stem in SPECIES:
    ns = "pet_" + stem.lower()
    body = "// GENERATED by tools/gen_mystery_units.py\n// The %s scene, compiled on its own for the mystery egg build.\n" % stem.lower()
    body += "#undef PET_MYSTERY\n#define PET_MYSTERY_TU 1\n"
    if flag:
        body += "#define %s 1\n" % flag
    body += "#define PET_NS %s\n" % ns
    body += '#include "%s"\n' % ("WolfInsect.cpp" if stem == "Butterfly" else "WolfScene.cpp")
    open(os.path.join(here, "Mystery%s.cpp" % stem), "w").write(body)
f = "// GENERATED by tools/gen_mystery_units.py\n#include \"WolfScene.h\"\n#if PET_MYST\n"
for pid, flag, stem in SPECIES:
    f += "extern PetSceneBase* make_pet_%s(WolfGame*);\n" % stem.lower()
f += "PetSceneBase* makePetScene(uint8_t sp, WolfGame* g) {\n  switch (sp) {\n"
for pid, flag, stem in SPECIES:
    f += "    case %d: return make_pet_%s(g);\n" % (pid, stem.lower())
f += "    default: return make_pet_wolf(g);\n  }\n}\n#endif\n"
open(os.path.join(here, "MysteryFactory.cpp"), "w").write(f)
print("wrote", len(SPECIES) + 1, "files")
