def _S(pts, dx=0.0, dy=0.0):
    return [(x + dx, y + dy) for x, y in pts]


def _plume(base, deg, length, width, bend=0.0, taper=0.7):
    """a long feather / tail: a tapering ribbon from `base` heading `deg` (0 = right, 90 = down), bending by `bend` degrees"""
    import math
    n = 9
    cl, left, right = [], [], []
    x, y = base
    a = math.radians(deg)
    for i in range(n + 1):
        t = i / n
        cl.append((x, y))
        a2 = a + math.radians(bend) * t
        step = length / n
        x += math.cos(a2) * step
        y += math.sin(a2) * step
        w = width * (math.sin(math.pi * min(1.0, t ** taper * 0.97 + 0.03)) * 0.9 + 0.1)
        if taper < 0.7: w = width * (0.35 + 0.65 * math.sin(math.pi * (t * 0.9 + 0.05)))
        nx, ny = -math.sin(a2), math.cos(a2)
        left.append((cl[-1][0] + nx * w, cl[-1][1] + ny * w))
        right.append((cl[-1][0] - nx * w, cl[-1][1] - ny * w))
    return left + [(x, y)] + right[::-1]


def _fan(poly, base, angles):
    """several copies of a tail, rotated about its root: a kitsune's tails"""
    import math
    def rot(p, a):
        c, s = math.cos(a), math.sin(a)
        x, y = p[0] - base[0], p[1] - base[1]
        return (base[0] + x * c - y * s, base[1] + x * s + y * c)
    return [[rot(p, math.radians(a)) for p in poly] for a in angles]


def _shift_all(g, dx):
    """move a finished design to the right (room for a long tail)"""
    def sh(pts):
        return [(x + dx, y) for x, y in pts]
    g["BODY"] = sh(g["BODY"]); g["HEAD_SIDE"] = sh(g["HEAD_SIDE"])
    k = g["HEAD_SIDE_KEY"]; g["HEAD_SIDE_KEY"] = {n: (v[0] + dx, v[1]) for n, v in k.items()}
    g["EAR_SIDE"] = [sh(e) for e in g["EAR_SIDE"]]
    g["FCX"] += dx
    g["HEAD_FRONT"] = sh(g["HEAD_FRONT"])
    g["EAR_FRONT"] = [[sh(a), sh(b)] for a, b in g["EAR_FRONT"]]
    g["LEG_X"] = tuple(x + dx for x in g["LEG_X"])
    g["NECK"] = (g["NECK"][0] + dx, g["NECK"][1])
    g["TAILS"] = {k: [[sh(p) for p in f] if isinstance(f[0], list) else sh(f) for f in v] for k, v in g["TAILS"].items()}


